  function locale() {
    return document.documentElement.lang === "en" ? "en" : "vi";
  }

  function applyRefinedCopy() {
    const lang = locale();
    const dict = refined[lang];
    Object.entries(dict).forEach(([key, value]) => {
      document.querySelectorAll(`[data-i18n="${key}"]`).forEach(el => { el.textContent = value; });
      document.querySelectorAll(`[data-i18n-aria="${key}"]`).forEach(el => { el.setAttribute("aria-label", value); });
      document.querySelectorAll(`[data-i18n-alt="${key}"]`).forEach(el => { el.setAttribute("alt", value); });
    });
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.content = lang === "en"
      ? "VOLTIS — electric mobility brand and product experience prototype."
      : "VOLTIS — bản mẫu website thương hiệu và trải nghiệm xe điện.";
  }

  function bindLocaleRefinement() {
    document.querySelectorAll('.locale-switch__btn[data-locale]').forEach(button => {
      button.addEventListener("click", () => requestAnimationFrame(() => requestAnimationFrame(applyRefinedCopy)));
    });
  }

  applyRefinedCopy();
  bindLocaleRefinement();
  window.addEventListener("pageshow", applyRefinedCopy);
